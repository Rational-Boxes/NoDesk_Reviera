//! A small built-in stroke font for labels and annotation drawn by the renderer: capital
//! letters, digits and the punctuation of lengths (`. , ' " - /`). Lower-case letters use the
//! capital shapes, except `m`. No font files are needed, so labels look the same everywhere.
//! (Annotation text with real fonts comes with the text renderer, DOC-ANN-000.)

use glam::Vec3;

/// Character cell height in grid units; glyphs are drawn on a 4 × 6 grid.
const CELL: f32 = 6.0;

/// Strokes of a character on the 4 × 6 grid.
fn glyph(c: char) -> &'static [&'static [(f32, f32)]] {
    match c {
        'A' => &[&[(0., 0.), (2., 6.), (4., 0.)], &[(1., 3.), (3., 3.)]],
        // A padlock, for locked dimensions (ARC-CNST-001).
        '\u{1F512}' => &[
            &[(0.3, 0.), (3.7, 0.), (3.7, 3.4), (0.3, 3.4), (0.3, 0.)],
            &[(1.0, 3.4), (1.0, 4.8), (2.0, 5.8), (3.0, 4.8), (3.0, 3.4)],
        ],
        // A superscript 2, for square metres.
        '²' => &[&[
            (0., 5.),
            (0.5, 6.),
            (2., 6.),
            (2.5, 5.),
            (0., 3.),
            (2.5, 3.),
        ]],
        'B' => &[
            &[
                (0., 0.),
                (0., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (3., 3.),
                (0., 3.),
            ],
            &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)],
        ],
        'C' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.)]],
        'D' => &[&[
            (0., 0.),
            (0., 6.),
            (3., 6.),
            (4., 5.),
            (4., 1.),
            (3., 0.),
            (0., 0.),
        ]],
        'E' => &[
            &[(4., 6.), (0., 6.), (0., 0.), (4., 0.)],
            &[(0., 3.), (3., 3.)],
        ],
        'F' => &[&[(4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (2., 3.)]],
        'H' => &[
            &[(0., 0.), (0., 6.)],
            &[(4., 0.), (4., 6.)],
            &[(0., 3.), (4., 3.)],
        ],
        'I' => &[
            &[(2., 0.), (2., 6.)],
            &[(1., 6.), (3., 6.)],
            &[(1., 0.), (3., 0.)],
        ],
        'J' => &[&[(4., 6.), (4., 0.), (0., 0.), (0., 2.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 6.), (0., 3.), (4., 0.)]],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'O' => &[&[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)]],
        'P' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.)]],
        'Q' => &[
            &[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)],
            &[(2.5, 1.5), (4.5, -1.)],
        ],
        'R' => &[
            &[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.)],
            &[(1., 3.), (4., 0.)],
        ],
        'S' | '5' => &[&[(4., 6.), (0., 6.), (0., 3.), (4., 3.), (4., 0.), (0., 0.)]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 0.), (4., 0.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (1., 0.), (2., 3.), (3., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        'm' => &[
            &[(0., 0.), (0., 4.), (2., 4.), (2., 0.)],
            &[(2., 4.), (4., 4.), (4., 0.)],
        ],
        '0' => &[
            &[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)],
            &[(0.6, 0.6), (3.4, 5.4)],
        ],
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        '2' => &[&[(0., 6.), (4., 6.), (4., 3.), (0., 3.), (0., 0.), (4., 0.)]],
        '3' => &[
            &[(0., 6.), (4., 6.), (4., 0.), (0., 0.)],
            &[(1., 3.), (4., 3.)],
        ],
        '4' => &[&[(0., 6.), (0., 3.), (4., 3.)], &[(3., 6.), (3., 0.)]],
        '6' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (0., 3.)]],
        '7' => &[&[(0., 6.), (4., 6.), (1., 0.)]],
        '8' => &[
            &[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)],
            &[(0., 3.), (4., 3.)],
        ],
        '9' => &[&[(4., 3.), (0., 3.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)]],
        '.' => &[&[(0.6, 0.), (1.4, 0.), (1.4, 0.8), (0.6, 0.8), (0.6, 0.)]],
        ',' => &[&[(1., 0.8), (1., 0.), (0.4, -1.)]],
        '-' => &[&[(0.5, 3.), (3.5, 3.)]],
        '/' => &[&[(0., 0.), (3., 6.)]],
        '\'' => &[&[(1., 6.), (1., 4.4)]],
        '"' => &[&[(0.5, 6.), (0.5, 4.4)], &[(1.7, 6.), (1.7, 4.4)]],
        c if c.is_ascii_lowercase() => glyph(c.to_ascii_uppercase()),
        _ => &[],
    }
}

/// Horizontal advance of a character, in grid units.
fn advance(c: char) -> f32 {
    match c {
        '.' | ',' | '\'' => 2.4,
        '"' => 3.2,
        ' ' => 3.0,
        '1' => 4.5,
        '/' => 4.0,
        '²' => 3.5,
        _ => 5.5,
    }
}

/// The width of `text` set `height` tall.
pub fn width(text: &str, height: f32) -> f32 {
    let unit = height / CELL;
    let total: f32 = text.chars().map(advance).sum();
    (total - 1.5).max(0.0) * unit
}

/// The strokes of `text` as line segments: starting at `origin` (bottom left), reading along
/// `right`, with `up` upward, letters `height` tall.
pub fn strokes(text: &str, origin: Vec3, right: Vec3, up: Vec3, height: f32) -> Vec<[Vec3; 2]> {
    let unit = height / CELL;
    let mut out = Vec::new();
    let mut x = 0.0;
    for c in text.chars() {
        let at = origin + right * (x * unit);
        for line in glyph(c) {
            for pair in line.windows(2) {
                let p = |(gx, gy): (f32, f32)| at + right * (gx * unit) + up * (gy * unit);
                out.push([p(pair[0]), p(pair[1])]);
            }
        }
        x += advance(c);
    }
    out
}
