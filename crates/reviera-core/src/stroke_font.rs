//! Reviera's built-in stroke font (capital letters, digits and the punctuation of lengths):
//! the glyph strokes the renderer draws labels with, and model text is built from
//! (ARC-MTXT-001). No font files are needed, so text looks the same everywhere.

/// Character cell height in grid units; glyphs are drawn on a 4 × 6 grid.
pub const CELL: f32 = 6.0;

/// Strokes of a character on the 4 × 6 grid.
pub fn glyph(c: char) -> &'static [&'static [(f32, f32)]] {
    match c {
        'A' => &[&[(0., 0.), (2., 6.), (4., 0.)], &[(1., 3.), (3., 3.)]],
        // Bar diameter, for rebar labels (STR-RBR-018): a circle struck through.
        'Ø' | 'ø' | '⌀' => &[
            &[(1., 0.5), (3., 0.5), (4., 2.), (4., 4.), (3., 5.5), (1., 5.5), (0., 4.), (0., 2.), (1., 0.5)],
            &[(-0.3, 0.), (4.3, 6.)],
        ],
        // "@" for spacings: a ring with a tail.
        '@' => &[&[(3., 2.), (3., 4.), (1.5, 4.), (1.5, 2.), (3., 2.), (4., 2.5), (4., 5.), (3., 6.), (1., 6.), (0., 5.), (0., 1.), (1., 0.), (4., 0.)]],
        ':' => &[&[(2., 1.), (2., 1.6)], &[(2., 4.), (2., 4.6)]],
        // A padlock, for locked dimensions (ARC-CNST-001).
        '\u{1F512}' => &[
            &[(0.3, 0.), (3.7, 0.), (3.7, 3.4), (0.3, 3.4), (0.3, 0.)],
            &[(1.0, 3.4), (1.0, 4.8), (2.0, 5.8), (3.0, 4.8), (3.0, 3.4)],
        ],
        // A superscript 2, for square metres.
        '²' => &[&[
            (0., 5.),
            (0.5, 6.),
            (2., 6.),
            (2.5, 5.),
            (0., 3.),
            (2.5, 3.),
        ]],
        '³' => &[&[(0., 6.), (2.5, 6.), (2.5, 3.), (0., 3.)], &[(0.8, 4.5), (2.5, 4.5)]],
        'B' => &[
            &[
                (0., 0.),
                (0., 6.),
                (3., 6.),
                (4., 5.),
                (4., 4.),
                (3., 3.),
                (0., 3.),
            ],
            &[(3., 3.), (4., 2.), (4., 1.), (3., 0.), (0., 0.)],
        ],
        'C' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.)]],
        'D' => &[&[
            (0., 0.),
            (0., 6.),
            (3., 6.),
            (4., 5.),
            (4., 1.),
            (3., 0.),
            (0., 0.),
        ]],
        'E' => &[
            &[(4., 6.), (0., 6.), (0., 0.), (4., 0.)],
            &[(0., 3.), (3., 3.)],
        ],
        'F' => &[&[(4., 6.), (0., 6.), (0., 0.)], &[(0., 3.), (3., 3.)]],
        'G' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (2., 3.)]],
        'H' => &[
            &[(0., 0.), (0., 6.)],
            &[(4., 0.), (4., 6.)],
            &[(0., 3.), (4., 3.)],
        ],
        'I' => &[
            &[(2., 0.), (2., 6.)],
            &[(1., 6.), (3., 6.)],
            &[(1., 0.), (3., 0.)],
        ],
        'J' => &[&[(4., 6.), (4., 0.), (0., 0.), (0., 2.)]],
        'K' => &[&[(0., 0.), (0., 6.)], &[(4., 6.), (0., 3.), (4., 0.)]],
        'L' => &[&[(0., 6.), (0., 0.), (4., 0.)]],
        'M' => &[&[(0., 0.), (0., 6.), (2., 3.), (4., 6.), (4., 0.)]],
        'N' => &[&[(0., 0.), (0., 6.), (4., 0.), (4., 6.)]],
        'O' => &[&[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)]],
        'P' => &[&[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.)]],
        'Q' => &[
            &[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)],
            &[(2.5, 1.5), (4.5, -1.)],
        ],
        'R' => &[
            &[(0., 0.), (0., 6.), (4., 6.), (4., 3.), (0., 3.)],
            &[(1., 3.), (4., 0.)],
        ],
        'S' | '5' => &[&[(4., 6.), (0., 6.), (0., 3.), (4., 3.), (4., 0.), (0., 0.)]],
        'T' => &[&[(0., 6.), (4., 6.)], &[(2., 6.), (2., 0.)]],
        'U' => &[&[(0., 6.), (0., 0.), (4., 0.), (4., 6.)]],
        'V' => &[&[(0., 6.), (2., 0.), (4., 6.)]],
        'W' => &[&[(0., 6.), (1., 0.), (2., 3.), (3., 0.), (4., 6.)]],
        'X' => &[&[(0., 0.), (4., 6.)], &[(0., 6.), (4., 0.)]],
        'Y' => &[&[(0., 6.), (2., 3.), (4., 6.)], &[(2., 3.), (2., 0.)]],
        'Z' => &[&[(0., 6.), (4., 6.), (0., 0.), (4., 0.)]],
        'm' => &[
            &[(0., 0.), (0., 4.), (2., 4.), (2., 0.)],
            &[(2., 4.), (4., 4.), (4., 0.)],
        ],
        '0' => &[
            &[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)],
            &[(0.6, 0.6), (3.4, 5.4)],
        ],
        '1' => &[&[(1., 5.), (2., 6.), (2., 0.)], &[(1., 0.), (3., 0.)]],
        '2' => &[&[(0., 6.), (4., 6.), (4., 3.), (0., 3.), (0., 0.), (4., 0.)]],
        '3' => &[
            &[(0., 6.), (4., 6.), (4., 0.), (0., 0.)],
            &[(1., 3.), (4., 3.)],
        ],
        '4' => &[&[(0., 6.), (0., 3.), (4., 3.)], &[(3., 6.), (3., 0.)]],
        '6' => &[&[(4., 6.), (0., 6.), (0., 0.), (4., 0.), (4., 3.), (0., 3.)]],
        '7' => &[&[(0., 6.), (4., 6.), (1., 0.)]],
        '8' => &[
            &[(0., 0.), (4., 0.), (4., 6.), (0., 6.), (0., 0.)],
            &[(0., 3.), (4., 3.)],
        ],
        '9' => &[&[(4., 3.), (0., 3.), (0., 6.), (4., 6.), (4., 0.), (0., 0.)]],
        '.' => &[&[(0.6, 0.), (1.4, 0.), (1.4, 0.8), (0.6, 0.8), (0.6, 0.)]],
        ',' => &[&[(1., 0.8), (1., 0.), (0.4, -1.)]],
        '-' | '–' | '—' | '\u{2212}' => &[&[(0.5, 3.), (3.5, 3.)]],
        '/' => &[&[(0., 0.), (3., 6.)]],
        '\'' => &[&[(1., 6.), (1., 4.4)]],
        '"' => &[&[(0.5, 6.), (0.5, 4.4)], &[(1.7, 6.), (1.7, 4.4)]],
        // Brackets, signs and the ellipsis, for menu labels (UI-SEL-007).
        '(' => &[&[(2.5, 6.5), (1., 4.5), (1., 1.5), (2.5, -0.5)]],
        ')' => &[&[(1.5, 6.5), (3., 4.5), (3., 1.5), (1.5, -0.5)]],
        '+' => &[&[(0.5, 3.), (3.5, 3.)], &[(2., 1.5), (2., 4.5)]],
        // Plus over a bar: zero elevations read ±0.
        '±' => &[&[(0.5, 3.5), (3.5, 3.5)], &[(2., 2.), (2., 5.)], &[(0.5, 0.8), (3.5, 0.8)]],
        '|' => &[&[(2., -0.5), (2., 6.5)]],
        '<' => &[&[(3.5, 5.), (0.5, 3.), (3.5, 1.)]],
        '>' | '›' => &[&[(0.5, 5.), (3.5, 3.), (0.5, 1.)]],
        '?' => &[&[(0., 5.), (1., 6.), (3., 6.), (4., 5.), (4., 4.), (2., 3.), (2., 1.6)], &[(2., 0.), (2., 0.6)]],
        '&' => &[&[(4., 0.), (0.5, 4.), (0.5, 5.5), (1.5, 6.), (2.5, 5.5), (2.5, 4.5), (0., 2.), (0., 0.5), (1., 0.), (2.5, 0.), (4., 2.)]],
        '…' => &[
            &[(0., 0.), (0.9, 0.), (0.9, 0.9), (0., 0.9), (0., 0.)],
            &[(1.8, 0.), (2.7, 0.), (2.7, 0.9), (1.8, 0.9), (1.8, 0.)],
            &[(3.6, 0.), (4.5, 0.), (4.5, 0.9), (3.6, 0.9), (3.6, 0.)],
        ],
        c if c.is_ascii_lowercase() => glyph(c.to_ascii_uppercase()),
        _ => &[],
    }
}

/// Horizontal advance of a character, in grid units.
pub fn advance(c: char) -> f32 {
    match c {
        '.' | ',' | '\'' => 2.4,
        '"' => 3.2,
        ' ' => 3.0,
        '1' => 4.5,
        '/' => 4.0,
        ':' => 3.0,
        '(' | ')' | '|' => 4.0,
        '²' | '³' => 3.5,
        _ => 5.5,
    }
}
